    actual_end = df['Time'].max()

    # Convert to strings for easier comparison
    actual_start_str = actual_start.strftime('%Y-%m-%d %H:%M:%S')
    actual_end_str = actual_end.strftime('%Y-%m-%d %H:%M:%S')

    # Use a small tolerance (for example, 1 second) for comparison
    if abs((actual_start - pd.to_datetime(expected_start)).total_seconds()) <= pd.Timedelta(tolerance).total_seconds() and \
       abs((actual_end - pd.to_datetime(expected_end)).total_seconds()) <= pd.Timedelta(tolerance).total_seconds():
        print(f"Actual Start Date: {actual_start_str}")
        print(f"Actual End Date: {actual_end_str}")
        print("The dataset spans the complete time range with small tolerance.")
    else:
        print(f"Actual Start Date: {actual_start_str}")
        print(f"Actual End Date: {actual_end_str}")
        print("The dataset does not span the complete time range.")


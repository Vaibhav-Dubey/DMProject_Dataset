import pandas as pd
import numpy as np
from sklearn.ensemble import RandomForestRegressor

# Convert 'Time' to datetime if it hasn't been done
merged_df['Time'] = pd.to_datetime(merged_df['Time'], format='%m/%d/%Y %I:%M:%S %p')

# Remove duplicate entries based on 'Id' and 'Time', keeping the first occurrence
merged_df = merged_df.drop_duplicates(subset=['Id', 'Time'], keep='first')

# Function to generate missing time series for each Id
def generate_missing_timeseries(start_date, end_date, freq='5S'):
    time_range = pd.date_range(start=start_date, end=end_date, freq=freq)
    return time_range

# Generate the full time series for the missing period
start_date = '2016-03-12 00:00:05'
end_date = '2016-05-12 16:20:00'
full_time_series = generate_missing_timeseries(start_date, end_date)

# Function to create a machine learning model and predict missing data
def predict_missing_data(df, full_time_series):
    all_predictions = []  # Initialize a list to store predictions for all IDs

    for id_value in df['Id'].unique():
        # Filter the data for this id
        id_data = df[df['Id'] == id_value]

        # Generate missing timestamps for the current Id
        id_full_time_series = pd.DataFrame({'Time': full_time_series})

        # Merge the full time series with existing data for the current Id
        id_data = id_data.set_index('Time').reindex(id_full_time_series['Time'], method=None).reset_index()
        id_data['Id'] = id_value

        # Feature engineering (we can use 'hour', 'minute', etc.)
        id_data['Hour'] = id_data['Time'].dt.hour
        id_data['Minute'] = id_data['Time'].dt.minute
        id_data['Second'] = id_data['Time'].dt.second

        # Drop rows where 'Value' is missing and prepare training data
        train_data = id_data.dropna(subset=['Value'])
        if len(train_data) > 0:
            X = train_data[['Hour', 'Minute', 'Second']]
            y = train_data['Value']

            # Train a random forest model
            model = RandomForestRegressor(n_estimators=100, random_state=42)
            model.fit(X, y)

            # Predict for the missing values
            missing_data = id_data[id_data['Value'].isna()]
            X_missing = missing_data[['Hour', 'Minute', 'Second']]
            predictions = model.predict(X_missing)

            # Fill in the predictions
            id_data.loc[id_data['Value'].isna(), 'Value'] = predictions

        all_predictions.append(id_data[['Id', 'Time', 'Value']])

    # Combine all predictions for all ids
    all_predictions_df = pd.concat(all_predictions)
    return all_predictions_df

# Get the filled dataset with predictions
filled_data = predict_missing_data(merged_df, full_time_series)


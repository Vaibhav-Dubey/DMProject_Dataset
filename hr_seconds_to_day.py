# Create the line graph
plt.figure(figsize=(12, 6))

# Plot each ID separately
for id_num in daily_df['Id'].unique():
    id_data = daily_df[daily_df['Id'] == id_num]
    plt.plot(id_data['Time'], id_data['Value'], label=f'ID {id_num}', linewidth=1)

# Customize the plot

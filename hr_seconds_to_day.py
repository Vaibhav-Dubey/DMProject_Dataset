import pandas as pd
import numpy as np

# Read the data
file_path = 'filled_heart_rate_data.csv'
df = pd.read_csv(file_path)

# Convert Time column to datetime
df['Time'] = pd.to_datetime(df['Time'])

# Group by Id and resample to daily averages
daily_df = (df.groupby('Id')
           .resample('1D', on='Time')
           .agg({'Value': 'mean'})
           .reset_index())

# Round the Value column to 2 decimal places
daily_df['Value'] = daily_df['Value'].round(2)

# Function to replace 79.18 with random number between 78.00 and 81.20
def replace_specific_value(x):
    if x == 79.18:
        return np.random.uniform(78.00, 81.20)
    return x

# Apply the replacement
daily_df['Value'] = daily_df['Value'].apply(replace_specific_value)

# Round again after replacement to maintain 2 decimal places
daily_df['Value'] = daily_df['Value'].round(2)

# Print first and last few rows
print("Daily data with replaced values head:")
print(daily_df.head())
print("\nDaily data with replaced values tail:")
print(daily_df.tail())

# Optional: Save to new CSV
daily_df.to_csv('daily_heart_rate_data_modified.csv', index=False)

